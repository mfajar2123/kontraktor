test('WhatsApp dua admin, penutupan, dan peta Sukabumi', async ({ page, context }, testInfo) => {
  test.setTimeout(60000)
  await context.route('https://wa.me/**', route => route.fulfill({ status: 200, contentType: 'text/html', body: '<title>WhatsApp test</title>' }))
  await page.goto('/kontak')
  const trigger = page.getByRole('button', { name: 'Hubungi melalui WhatsApp', exact: true })
  await expect(trigger).toBeVisible()
  await trigger.click()
  await expect(page.locator('.whatsapp-panel')).toBeVisible()
  await expect(page.locator('.whatsapp-admin')).toHaveCount(2)
  const bounds = await page.locator('.whatsapp-panel').boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.keyboard.press('Escape')
  await expect(page.locator('.whatsapp-panel')).not.toBeVisible()
  await expect(trigger).toBeFocused()
  for (const [name, number] of [['Admin 1', '6281200000001'], ['Admin 2', '6281200000002']]) {
    await trigger.click()
    const link = page.getByRole('link', { name: 'Hubungi ' + name + ' melalui WhatsApp (tab baru)' })
    await expect(link).toHaveAttribute('href', new RegExp('https://wa.me/' + number))
    const popupPromise = context.waitForEvent('page')
    await link.click()
    const popup = await popupPromise
    await expect(popup).toHaveURL(new RegExp('https://wa.me/' + number))
    await popup.close()
    await expect(page.locator('.whatsapp-panel')).not.toBeVisible()
  }
  const map = page.getByTitle('Peta lokasi kantor dummy di Sukabumi')
  await map.scrollIntoViewIfNeeded()
  await expect(map).toHaveAttribute('src', /google.com\/maps\?q=-6.9210%2C106.9270/)
  await expect(page.getByRole('link', { name: 'Petunjuk Arah' })).toHaveAttribute('href', /destination=-6.9210%2C106.9270/)
  await expect(page.frameLocator('iframe.office-map').locator('body')).toBeVisible({ timeout: 20000 })
  await page.evaluate(() => {
    (document.activeElement as HTMLElement)?.blur()
    window.scrollTo({ top: 0, behavior: 'instant' })
  })
  await page.screenshot({ path: 'artifacts/kontak-' + testInfo.project.name + '.png', fullPage: true })
  await trigger.click()
  await page.screenshot({ path: 'artifacts/whatsapp-' + testInfo.project.name + '.png' })
  await page.keyboard.press('Escape')
  await page.goto('/')
  await expect(page.locator('.whatsapp-float')).toHaveCount(0)
  await expect(page.locator('.achievement-section')).toHaveCount(0)
})
