test('tangkapan tampilan dan aset hero', async ({ page }, testInfo) => {
  test.setTimeout(60000)
  await page.goto('/')
  await expect(page.locator('.hero-photo img')).toBeVisible()
  await expect.poll(() => page.locator('.hero-photo img').evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0), { timeout: 30000 }).toBe(true)
  for (const image of await page.locator('main img').all()) {
    await image.scrollIntoViewIfNeeded()
    await expect.poll(() => image.evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0), { timeout: 15000 }).toBe(true)
  }
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await page.screenshot({ path: 'artifacts/beranda-' + testInfo.project.name + '.png', fullPage: true })
})
