import { test, expect } from '@playwright/test'
const routes = ['/', '/tentang-kami', '/layanan', '/layanan/konstruksi-gedung', '/layanan/renovasi-interior', '/layanan/perencanaan', '/layanan/infrastruktur', '/galeri', '/proyek/gedung-perkantoran', '/proyek/hunian-tropis', '/proyek/ruang-kolaborasi', '/proyek/pengembangan-kawasan', '/proyek/pusat-usaha', '/proyek/studio-kreatif', '/artikel', '/artikel/merencanakan-anggaran', '/artikel/renovasi-ruang-kerja', '/artikel/koordinasi-proyek', '/kontak', '/faq', '/kebijakan-privasi']
test('halaman perusahaan, metadata, dan tata letak', async ({ page }) => {
  test.setTimeout(90000)
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (/hydration/i.test(m.text())) errors.push(m.text()) })
  const titles = new Set()
  for (const route of routes) {
    const response = await page.goto(route)
    expect(response?.status(), route).toBe(200)
    await expect(page.locator('html')).toHaveAttribute('lang', 'id')
    await expect(page.locator('h1')).toHaveCount(1)
    await expect(page.locator('meta[name="description"]')).toHaveAttribute('content', /.+/)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), route).toBe(true)
    expect(await page.locator('main').innerText()).not.toMatch(/Muhamad Fajar|Full Stack Developer/)
    titles.add(await page.title())
  }
  expect(titles.size).toBe(routes.length)
  expect(errors).toEqual([])
})
